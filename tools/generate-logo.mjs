// Draws the Humble Planning mark as Android vector drawables, from the shapes of the logo
// (public/branding-defaults on the server: the mark is only a bitmap there). `node tools/generate-logo.mjs`
import { writeFileSync } from 'node:fs';

const res = new URL('../app/src/main/res/drawable/', import.meta.url);

// Outline of the two interlocked links, in the coordinates of the logo bitmap
const LINK_RIGHT = [[1504,67],[1755,0],[1755,417],[1385,516],[1385,277],[1285,304],[1285,757],[1216,775],[1216,251],[1454,188],[1454,426],[1686,364],[1686,90],[1573,120],[1573,573],[1504,591]];
const LINK_LEFT = [[820,464],[1165,372],[1165,610],[1504,521],[1504,591],[1096,700],[1096,462],[889,517],[889,792],[1216,705],[1216,775],[820,881]];
// Where one strand passes under the other: a soft shadow gives the interlocking
const SHADOWS = [
  { points: [[1216,490],[1285,472],[1285,579],[1216,597]], from: [1250,490], to: [1250,590] },
  { points: [[1504,306],[1573,288],[1573,394],[1504,412]], from: [1538,306], to: [1538,405] },
  { points: [[1216,668],[1285,650],[1285,700],[1216,705]], from: [1250,700], to: [1250,650] },
  { points: [[1504,484],[1573,465],[1573,520],[1504,521]], from: [1538,520], to: [1538,465] },
];
const BOUNDS = { x: 820, y: 0, width: 935, height: 881 };

const VIOLET_DEEP = '#FF5A17FF';
const VIOLET_LIGHT = '#FFCF9BFF';

const place = (size, inner) => {
  const scale = inner / Math.max(BOUNDS.width, BOUNDS.height);
  const dx = (size - BOUNDS.width * scale) / 2;
  const dy = (size - BOUNDS.height * scale) / 2;
  return ([x, y]) => [+(dx + (x - BOUNDS.x) * scale).toFixed(2), +(dy + (y - BOUNDS.y) * scale).toFixed(2)];
};
const path = (points, at) => 'M' + points.map(at).map(([x, y]) => `${x},${y}`).join('L') + 'Z';

const header = (size, extra = '') =>
  `<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tools/generate-logo.mjs -->\n<vector xmlns:android="http://schemas.android.com/apk/res/android"${extra}\n    android:width="${size}dp"\n    android:height="${size}dp"\n    android:viewportWidth="${size}"\n    android:viewportHeight="${size}">\n`;

function colored(size, inner) {
  const at = place(size, inner);
  const [sx, sy] = at([BOUNDS.x, BOUNDS.y + BOUNDS.height]);
  const [ex, ey] = at([BOUNDS.x + BOUNDS.width, BOUNDS.y]);
  const gradient = `        <aapt:attr name="android:fillColor">
            <gradient android:type="linear" android:startX="${sx}" android:startY="${sy}" android:endX="${ex}" android:endY="${ey}">
                <item android:color="${VIOLET_DEEP}" android:offset="0" />
                <item android:color="${VIOLET_LIGHT}" android:offset="1" />
            </gradient>
        </aapt:attr>\n`;
  let out = header(size, '\n    xmlns:aapt="http://schemas.android.com/aapt"');
  for (const link of [LINK_RIGHT, LINK_LEFT]) {
    out += `    <path android:pathData="${path(link, at)}">\n${gradient}    </path>\n`;
  }
  for (const shadow of SHADOWS) {
    const [x1, y1] = at(shadow.from);
    const [x2, y2] = at(shadow.to);
    out += `    <path android:pathData="${path(shadow.points, at)}">
        <aapt:attr name="android:fillColor">
            <gradient android:type="linear" android:startX="${x1}" android:startY="${y1}" android:endX="${x2}" android:endY="${y2}">
                <item android:color="#00230A6E" android:offset="0" />
                <item android:color="#99230A6E" android:offset="1" />
            </gradient>
        </aapt:attr>
    </path>\n`;
  }
  return out + '</vector>\n';
}

function flat(size, inner, color) {
  const at = place(size, inner);
  let out = header(size);
  for (const link of [LINK_RIGHT, LINK_LEFT]) out += `    <path android:fillColor="${color}" android:pathData="${path(link, at)}" />\n`;
  return out + '</vector>\n';
}

// Adaptive icon: 108 dp canvas, content inside the 66 dp safe zone
writeFileSync(new URL('ic_launcher_foreground.xml', res), colored(108, 56));
writeFileSync(new URL('ic_launcher_monochrome.xml', res), flat(108, 56, '#FF000000'));
writeFileSync(new URL('ic_notification.xml', res), flat(24, 20, '#FFFFFFFF'));
writeFileSync(new URL('ic_logo_mark.xml', res), colored(96, 96));
writeFileSync(new URL('ic_launcher_background.xml', res),
  `<?xml version="1.0" encoding="utf-8"?>\n<shape xmlns:android="http://schemas.android.com/apk/res/android">\n    <solid android:color="#FFFFFFFF" />\n</shape>\n`);
